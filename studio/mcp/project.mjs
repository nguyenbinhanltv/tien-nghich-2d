// THE ONLY MODULE IN studio/mcp THAT READS PROJECT FILES.
//
// The project is described by its pack (`studio.project.json`, loaded and validated by studio/core).
// Every data file this module reads (palette, catalog sources) is named by the pack, not hard-coded
// here. Tools never see paths or raw JSON, only a snapshot's methods.
//
// `openProject(root).snapshot()` loads the pack and files ONCE and returns a consistent view; a tool
// takes one snapshot per call, so all sections of a response come from the same moment and nothing
// is cached across calls (a long-lived server never reports stale counts).

import { existsSync, readFileSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { loadPackSync, packFileName } from '../core/pack.mjs';
import { openWorkspace } from '../core/workspace.mjs';
import { loadAssetIndex } from './asset-index.mjs';
import { ToolError } from './registry.mjs';

// A ToolError so a missing or half-written file reaches the model as an actionable isError result
// ("assets/manifest.json is not valid JSON: ...") instead of a generic "failed unexpectedly".
export class ProjectError extends ToolError {}

// Facts the pack does not carry yet (docs/ART_BIBLE.md, tools/scripts/qa_assets.py). Candidates to
// move into the pack; until then they are data here, with their sources named in the output.
const OUTLINE_CATEGORIES = {
  widthPx: 1,
  appliesToCategories: ['player', 'mob', 'boss', 'weapon', 'prop', 'icon'],
  exemptCategories: ['tileset', 'ui', 'projectile', 'vfx'],
  note: 'Every silhouette-edge pixel of an applicable sprite must be the outline colour; 2x2 outline blocks are a warning.',
  source: 'docs/ART_BIBLE.md; tools/scripts/qa_assets.py (OUTLINE_CATEGORIES)',
};
const ALPHA_BINARY = {
  values: [0, 255],
  transparentPixelRgb: [0, 0, 0],
  paletteOnly: true,
  note: 'Alpha is binary. RGB under alpha 0 must be 0,0,0. Every opaque pixel must be a palette colour.',
  source: 'docs/ART_BIBLE.md; tools/scripts/qa_assets.py (partial_alpha, dirty_transparent, off_palette)',
};
// Atlas-packer key groups (assets/atlases/AssetKeys.ts, generated by tools/scripts/pack_atlases.py).
const PACKER_KEY_GROUPS = {
  characters: 'player, mob, boss',
  tilesets: 'tileset',
  weapons: 'weapon',
  projectiles: 'projectile',
  props: 'prop',
  ui: 'ui, icon',
};
// Pack frameKeys entries this module presents under a richer scope; any other entry is passed through.
const KNOWN_FRAME_KEYS = ['ui', 'vfx', 'longtime', 'longtimeVfx'];

const tally = (items, keyFn) => {
  const out = {};
  for (const it of items) {
    const k = keyFn(it) ?? 'unknown';
    out[k] = (out[k] ?? 0) + 1;
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => (a < b ? -1 : 1)));
};

export function openProject(rootArg, { libraryDir } = {}) {
  const root = resolve(rootArg);
  if (!existsSync(root) || !statSync(root).isDirectory()) throw new ProjectError(`project path is not a directory: ${root}`);

  const readJson = (rel) => {
    const p = join(root, rel);
    if (!existsSync(p)) throw new ProjectError(`missing ${rel} under ${root} (named by ${packFileName}; is --project the repo root?)`);
    try {
      return JSON.parse(readFileSync(p, 'utf8'));
    } catch (e) {
      throw new ProjectError(`${rel} is not valid JSON: ${e.message}`);
    }
  };

  const loadPack = () => {
    if (!existsSync(join(root, packFileName))) throw new ProjectError(`missing ${packFileName} under ${root} (is --project the repo root?)`);
    try {
      // verifyFiles:false: this server reads only some of the files the pack names, and reports a
      // missing one by name when it actually needs it.
      return loadPackSync(root, packFileName, { verifyFiles: false });
    } catch (e) {
      throw new ProjectError(e.code === 'invalid_pack' ? e.message : `${packFileName} could not be loaded: ${e.message}`);
    }
  };

  const snapshot = () => {
    const pack = loadPack();
    const source = (kind) => {
      const s = pack.catalog.sources.find((x) => x.kind === kind);
      if (!s) throw new ProjectError(`${packFileName} has no catalog source of kind "${kind}"`);
      return s;
    };
    const coreSrc = source('asset-manifest');
    const designSrc = source('design-manifest');
    const audioSrc = source('audio-plan');
    const base = readJson(coreSrc.file);
    const longtime = readJson(designSrc.file);
    const audio = readJson(audioSrc.file);
    const paletteFile = readJson(pack.palette.file);

    const audioCounts = {};
    const walk = (o, path) => {
      for (const [k, v] of Object.entries(o ?? {})) {
        const p = [...path, k];
        if (Array.isArray(v) && v.every((x) => typeof x === 'string')) audioCounts[p.join('.')] = v.length;
        else if (v && typeof v === 'object' && p.length < 3) walk(v, p);
      }
    };
    walk(audio.core, ['core']);
    walk(audio.extensions, ['extensions']);

    const packRef = `${packFileName}`;
    return {
      root,
      source: 'project-pack',

      pack() {
        return { path: packFileName, present: true, consumed: true, id: pack.id, name: pack.name, version: pack.version };
      },

      palette() {
        const colors = paletteFile.colors.map((c) => ({ id: c.id, hex: c.hex, group: c.group }));
        return {
          name: paletteFile.name,
          version: paletteFile.version,
          outline: { id: paletteFile.outline_id, hex: paletteFile.outline },
          count: colors.length,
          colors,
          source: pack.palette.file,
        };
      },

      sizeClasses() {
        const profiles = {};
        for (const [name, p] of Object.entries(longtime.profiles)) {
          profiles[name] = {
            category: p.category,
            nativePx: p.native_px,
            pivotPx: p.pivot_px,
            directions: p.directions,
            clips: Object.fromEntries(Object.entries(p.clips).map(([c, [frames, ms]]) => [c, { frames, frameMs: ms }])),
          };
        }
        const baseSizes = {};
        for (const a of base.assets) {
          if (!Array.isArray(a.size)) continue;
          (baseSizes[a.category] ??= new Set()).add(a.size.join('x'));
        }
        return {
          packClasses: pack.sizeClasses,
          atlasProfiles: pack.atlasProfiles,
          longtimeProfiles: profiles,
          baseManifestSizes: Object.fromEntries(Object.entries(baseSizes).map(([k, v]) => [k, [...v].sort()])),
          mobileAtlas: longtime.mobile,
          source: `${packRef} (sizeClasses, atlasProfiles); ${designSrc.file} (profiles, mobile); ${coreSrc.file} (assets[].size)`,
        };
      },

      rules() {
        const o = pack.rules.outline;
        const hex = o.color === 'palette' ? paletteFile.outline : o.color;
        return {
          outline: {
            id: o.color === 'palette' ? paletteFile.outline_id : undefined,
            hex,
            mode: o.mode,
            borderIsEdge: o.borderIsEdge,
            ...OUTLINE_CATEGORIES,
          },
          alpha: { mode: pack.rules.alpha, ...ALPHA_BINARY },
          packSource: `${packRef} rules`,
        };
      },

      frameKeys() {
        const k = pack.frameKeys;
        const ui = base.delivery?.ui_export;
        const out = [
          ...Object.entries(PACKER_KEY_GROUPS).map(([group, cats]) => ({
            scope: `base:${cats}`,
            key: `${group}/{id}/{clip}_{direction}_{n}`,
            source: 'assets/atlases/AssetKeys.ts (generated by tools/scripts/pack_atlases.py)',
          })),
        ];
        if (k.vfx) out.push({ scope: 'base:vfx', key: k.vfx, source: `${packRef} frameKeys.vfx` });
        if (k.ui) out.push({ scope: 'base:ui (processed path)', key: k.ui, ...(ui?.processed ? { processed: ui.processed } : {}), source: `${packRef} frameKeys.ui` });
        if (k.longtime) {
          const d = longtime.defaults;
          out.push({ scope: 'longtime:sprites', key: k.longtime, raw: d.source, processed: d.processed, atlasExport: d.export, source: `${packRef} frameKeys.longtime; ${designSrc.file} defaults` });
        }
        if (k.longtimeVfx) {
          const v = longtime.vfx.paths;
          out.push({
            scope: 'longtime:vfx', key: k.longtimeVfx, raw: v.source, processed: v.processed,
            note: '{palette} replaces {direction}; "base" when an ID has one colour set. Indices start at 0.',
            source: `${packRef} frameKeys.longtimeVfx; ${designSrc.file} vfx.paths; docs/LONGTIME_VFX.md`,
          });
        }
        for (const [name, key] of Object.entries(k)) {
          if (!KNOWN_FRAME_KEYS.includes(name)) out.push({ scope: `pack:${name}`, key, source: `${packRef} frameKeys.${name}` });
        }
        out.push({
          scope: 'frame-file-name',
          pattern: '^(?P<anim>[a-z0-9]+(_[a-z0-9]+)*)_(?P<dir>south|east|north|west|none|f\\d+)_(?P<n>\\d+)$',
          note: 'Directions: south, east, north, west, none (single-view assets), fN (tile frame variants).',
          source: 'tools/scripts/qa_assets.py (NAME_RE)',
        });
        return out;
      },

      assetCounts() {
        const readinessDefault = longtime.defaults.readiness;
        const profileCategory = (a) => longtime.profiles[a.profile]?.category ?? a.profile;
        return {
          base: {
            manifest: coreSrc.file,
            total: base.assets.length,
            byCategory: tally(base.assets, (a) => a.category),
            byReadiness: tally(base.assets, (a) => a.readiness),
            byAssignedAgent: tally(base.assets, (a) => a.assigned_agent),
          },
          longtime: {
            manifest: designSrc.file,
            total: longtime.assets.length,
            byCategory: tally(longtime.assets, profileCategory),
            byReadiness: tally(longtime.assets, (a) => a.readiness ?? readinessDefault),
            byChunk: tally(longtime.assets, (a) => a.chunk_group),
            vfx: { total: longtime.vfx.entries.length, byStatus: tally(longtime.vfx.entries, (e) => e.status) },
          },
          audio: { manifest: audioSrc.file, idsByGroup: audioCounts, idTotal: Object.values(audioCounts).reduce((a, b) => a + b, 0) },
        };
      },

      manifests() {
        return [
          { path: coreSrc.file, schema: base.schema, version: base.version },
          { path: designSrc.file, schema: longtime.schema, version: longtime.version },
          { path: audioSrc.file, schema: audio.schema_version, version: audio.schema_version },
          { path: packFileName, schema: pack.schema, version: pack.version }, // appended: earlier entries keep their positions
        ];
      },
    };
  };

  snapshot(); // fail fast at startup: a bad project root is clearer on stderr than at the first call
  // The workspace is the studio core's view of the same directory (pack, palette, asset index, revision
  // store, studio database). It is built lazily, so a read-only project_info never opens SQLite.
  let workspace;
  return { root, source: 'project-pack', snapshot, get workspace() { return workspace ??= openWorkspace(root, { libraryDir, indexer: loadAssetIndex }); }, close() { workspace?.close(); } };
}
