// The pack reference of studio/README.md, generated from studio/schemas/project.schema.json so it cannot drift.
//   node studio/schemas/reference.mjs            print it
//   node studio/schemas/reference.mjs --write    rewrite the block between the markers in studio/README.md
//   node studio/schemas/reference.mjs --check    exit 1 when the README block is not what the schema produces
// reference.test.mjs runs the check, so a schema change without a README update fails the tests.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const SCHEMA_FILE = path.join(here, 'project.schema.json');
export const README_FILE = path.join(here, '..', 'README.md');
export const START = '<!-- pack-reference:start (generated by studio/schemas/reference.mjs; edit the schema, not this block) -->';
export const END = '<!-- pack-reference:end -->';

const oneLine = text => String(text ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const keys = node => Object.keys(node?.properties ?? {}).filter(k => k !== '$schema');
const typeOf = node => node.$ref ? node.$ref.split('/').pop() : node.const !== undefined ? `\`${JSON.stringify(node.const)}\`` : node.enum ? node.enum.map(v => `\`${v}\``).join(' or ') : node.type ?? (node.anyOf ? 'one of several' : 'any');

/** The markdown of the reference: one row per top-level block, then the nested keys of each block. */
export function renderReference(schema) {
  const required = new Set(schema.required);
  const blocks = Object.entries(schema.properties).filter(([name]) => name !== '$schema');
  const rows = blocks.map(([name, node]) => `| \`${name}\` | ${required.has(name) ? 'required' : 'optional'} | ${typeOf(node)} | ${oneLine(node.description) || '(a plain value)'} |`);
  const nested = blocks.filter(([, node]) => keys(node).length).map(([name, node]) => {
    const req = new Set(node.required ?? []);
    const lines = keys(node).map(key => {
      const child = node.properties[key];
      return `  - \`${name}.${key}\` (${req.has(key) ? 'required' : 'optional'}, ${typeOf(child)})${child.description ? `: ${oneLine(child.description)}` : ''}`;
    });
    return `- **\`${name}\`**\n${lines.join('\n')}`;
  });
  return [`The pack is \`studio.project.json\` (JSON Schema: \`studio/schemas/project.schema.json\`, version ${schema.properties.version.const}). ${blocks.length} top-level blocks; ${required.size} are required.`, '',
    '| Block | Needed | Type | What it holds |', '|---|---|---|---|', ...rows, '', 'Keys inside each block that has them:', '', ...nested].join('\n');
}

const block = body => `${START}\n\n${body}\n\n${END}`;

/** The README text with its reference block replaced (or an error when the markers are missing). */
export function withReference(readme, schema) {
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error('studio/README.md has no pack-reference block (start and end markers)');
  return readme.slice(0, a) + block(renderReference(schema)) + readme.slice(b + END.length);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const schema = JSON.parse(fs.readFileSync(SCHEMA_FILE, 'utf8'));
  const mode = process.argv[2];
  if (!mode) console.log(renderReference(schema));
  else {
    const readme = fs.readFileSync(README_FILE, 'utf8'), next = withReference(readme, schema);
    if (mode === '--check') { if (next !== readme) { console.error('studio/README.md pack reference is out of date: run node studio/schemas/reference.mjs --write'); process.exit(1); } console.log('pack reference is up to date'); }
    else if (mode === '--write') { fs.writeFileSync(README_FILE, next); console.log('studio/README.md pack reference written'); }
    else { console.error('usage: reference.mjs [--write | --check]'); process.exit(2); }
  }
}
