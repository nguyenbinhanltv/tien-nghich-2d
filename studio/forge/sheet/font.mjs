export const glyphWidth = 5, glyphHeight = 7;
export const canDraw = text => [...text].every(ch => Object.hasOwn(rows, ch));

/** Calls plot(x, y) for each lit pixel of `text` at integer `scale`, origin (x, y) top left, 1 glyph px gap. */
export function drawText(text, x, y, scale, plot) {
  let cursor = x;
  for (const ch of text) {
    const glyph = rows[ch];
    if (!glyph) throw new RangeError(`label character ${JSON.stringify(ch)} has no glyph`);
    glyph.split(' ').forEach((line, gy) => [...line].forEach((bit, gx) => {
      if (bit !== '1') return;
      for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) plot(cursor + gx * scale + sx, y + gy * scale + sy);
    }));
    cursor += (glyphWidth + 1) * scale;
  }
  return cursor - x - scale;
}
